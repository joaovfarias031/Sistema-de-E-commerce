class Endereco:
    def __init__(self, rua, numero, bairro, cidade, estado, cep):
        self.__rua = rua
        self.__numero = numero
        self.__bairro = bairro
        self.__cidade = cidade
        self.__estado = estado
        self.__cep = cep

    def atualizarEndereco(self, rua, numero, bairro, cidade, estado, cep):
        self.__rua = rua
        self.__numero = numero
        self.__bairro = bairro
        self.__cidade = cidade
        self.__estado = estado
        self.__cep = cep



             
